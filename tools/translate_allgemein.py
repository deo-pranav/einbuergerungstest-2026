# Format as JavaScript file matching bayern.js / allgemein.js format
def format_js(qs):
    lines = [
        "/*",
        " * Einbürgerungstest — die 300 bundesweiten Fragen (Teil I des Fragenkatalogs).",
        " *",
        " * TEXT: übernommen aus dem amtlichen \"Gesamtfragenkatalog zum Test",
        " *       'Leben in Deutschland' und zum 'Einbürgerungstest'\", Stand 07.05.2025",
        " *       (BAMF), maschinell aus dem PDF extrahiert.",
        " * LÖSUNGEN: nicht im amtlichen PDF enthalten. Der Antwortschlüssel wurde aus",
        " *       drei unabhängigen öffentlichen Datensätzen abgeglichen (siehe README).",
        " *       `srcs` gibt an, wie viele davon übereinstimmten — 3 = höchste,",
        " *       1 = nur eine Quelle. Es gab null Widersprüche zwischen den Quellen.",
        " *",
        " * Reihenfolge und Nummerierung folgen dem amtlichen Katalog (Aufgabe 1–300).",
        " * `correct` ist ein 0-basierter Index in `options`.",
        " * Bildfragen verweisen mit `image` auf eine Datei in assets/.",
        " *",
        " * Enthält vollständige englische Übersetzungen für alle 300 Fragen und Optionen.",
        " */",
        "window.ALLGEMEIN_QUESTIONS = ["
    ]

    for idx, q in enumerate(qs):
        lines.append("  {")
        lines.append(f"    id: {q['id']},")
        lines.append(f"    type: {json.dumps(q['type'])},")
        lines.append(f"    q: {json.dumps(q['q'], ensure_ascii=False)},")
        lines.append(f"    qEn: {json.dumps(q['qEn'], ensure_ascii=False)},")
        if 'cat' in q and q['cat']:
            lines.append(f"    cat: {json.dumps(q['cat'], ensure_ascii=False)},")
        if 'image' in q and q['image']:
            lines.append(f"    image: {json.dumps(q['image'], ensure_ascii=False)},")
        if 'credit' in q and q['credit']:
            lines.append(f"    credit: {json.dumps(q['credit'], ensure_ascii=False)},")
        
        lines.append("    options: [")
        for o_idx, opt in enumerate(q['options']):
            comma = "," if o_idx < len(q['options']) - 1 else ""
            t_de = json.dumps(opt['text'], ensure_ascii=False)
            t_en = json.dumps(opt['textEn'], ensure_ascii=False)
            lines.append(f"      {{ text: {t_de}, textEn: {t_en} }}{comma}")
        lines.append("    ],")
        lines.append(f"    correct: {q['correct']},")
        lines.append(f"    srcs: {q.get('srcs', 3)}")
        lines.append("  }" + ("," if idx < len(qs) - 1 else ""))

    lines.append("];")
    lines.append("")
    return "\n".join(lines)

js_content = format_js(questions)
with open('data/allgemein.js', 'w', encoding='utf-8') as f:
    f.write(js_content)

