for q in questions:
    qid = q['id']
    if qid in CUSTOM_Q_TRANSLATIONS:
        q['qEn'] = CUSTOM_Q_TRANSLATIONS[qid]
    elif q.get('qEn'):
        q['qEn'] = q['qEn'].replace('\n', ' ').replace('\r', '').strip()
        q['qEn'] = re.sub(r'\s+', ' ', q['qEn'])

    for opt in q['options']:
        text_de = opt['text'].strip()
        if text_de in OPT_TRANSLATIONS:
            opt['textEn'] = OPT_TRANSLATIONS[text_de]
        elif not opt.get('textEn') or len(opt['textEn']) == 0:
            clean_de = text_de.rstrip('.')
            if clean_de in OPT_TRANSLATIONS:
                opt['textEn'] = OPT_TRANSLATIONS[clean_de]
        
        if opt.get('textEn'):
            opt['textEn'] = opt['textEn'].replace('\n', ' ').replace('\r', '').strip()
            opt['textEn'] = re.sub(r'\s+', ' ', opt['textEn'])

